-- ============================================
-- QR Attendance Management System
-- Database Schema - Flyway Migration V1
-- MySQL 8.0+
-- ============================================

-- ============================================
-- TABLE 1: users
-- Core authentication table for all system users
-- ============================================
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    role VARCHAR(20) NOT NULL
        CHECK (role IN ('ADMIN', 'FACULTY', 'STUDENT')),

    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_role ON users(role);
CREATE INDEX idx_users_status ON users(account_status);

-- ============================================
-- TABLE 2: departments
-- Academic departments
-- ============================================
CREATE TABLE departments (
    department_id BIGINT NOT NULL AUTO_INCREMENT,
    department_code VARCHAR(30) NOT NULL,
    department_name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (department_id),
    UNIQUE KEY uk_departments_code (department_code),
    INDEX idx_departments_active (is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 3: student_profiles
-- Extended profile for student users
-- ============================================
CREATE TABLE student_profiles (
    student_id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    register_number VARCHAR(50) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    department_id BIGINT NOT NULL,
    year_of_study INT NOT NULL,
    section VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (student_id),
    UNIQUE KEY uk_student_user (user_id),
    UNIQUE KEY uk_student_register (register_number),
    INDEX idx_student_department (department_id),
    INDEX idx_student_year (year_of_study),
    CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON UPDATE CASCADE,
    CONSTRAINT fk_student_department FOREIGN KEY (department_id) REFERENCES departments(department_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 4: faculty_profiles
-- Extended profile for faculty users
-- ============================================
CREATE TABLE faculty_profiles (
    faculty_id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    employee_id VARCHAR(50) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    department_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (faculty_id),
    UNIQUE KEY uk_faculty_user (user_id),
    UNIQUE KEY uk_faculty_employee (employee_id),
    INDEX idx_faculty_department (department_id),
    CONSTRAINT fk_faculty_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON UPDATE CASCADE,
    CONSTRAINT fk_faculty_department FOREIGN KEY (department_id) REFERENCES departments(department_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 5: class_sections
-- Academic class sections within departments
-- ============================================
CREATE TABLE class_sections (
    section_id BIGINT NOT NULL AUTO_INCREMENT,
    department_id BIGINT NOT NULL,
    academic_year VARCHAR(20) NOT NULL,
    year_of_study INT NOT NULL,
    section_name VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (section_id),
    UNIQUE KEY uk_section_unique (department_id, academic_year, year_of_study, section_name),
    INDEX idx_section_department (department_id),
    INDEX idx_section_year (academic_year),
    CONSTRAINT fk_section_department FOREIGN KEY (department_id) REFERENCES departments(department_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 6: subjects
-- Academic subjects/courses
-- ============================================
CREATE TABLE subjects (
    subject_id BIGINT NOT NULL AUTO_INCREMENT,
    subject_code VARCHAR(30) NOT NULL,
    subject_name VARCHAR(150) NOT NULL,
    department_id BIGINT NOT NULL,
    credits INT NOT NULL DEFAULT 3,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (subject_id),
    UNIQUE KEY uk_subjects_code (subject_code),
    INDEX idx_subjects_department (department_id),
    CONSTRAINT fk_subjects_department FOREIGN KEY (department_id) REFERENCES departments(department_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 7: faculty_subject_assignments
-- Maps faculty to subjects and sections they teach
-- ============================================
CREATE TABLE faculty_subject_assignments (
    assignment_id BIGINT NOT NULL AUTO_INCREMENT,
    faculty_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    academic_year VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (assignment_id),
    UNIQUE KEY uk_assignment_unique (faculty_id, subject_id, section_id, academic_year),
    INDEX idx_assignment_faculty (faculty_id),
    INDEX idx_assignment_subject (subject_id),
    INDEX idx_assignment_section (section_id),
    CONSTRAINT fk_assignment_faculty FOREIGN KEY (faculty_id) REFERENCES faculty_profiles(faculty_id) ON UPDATE CASCADE,
    CONSTRAINT fk_assignment_subject FOREIGN KEY (subject_id) REFERENCES subjects(subject_id) ON UPDATE CASCADE,
    CONSTRAINT fk_assignment_section FOREIGN KEY (section_id) REFERENCES class_sections(section_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 8: enrollments
-- Student enrollment in class sections
-- ============================================
CREATE TABLE enrollments (
    enrollment_id BIGINT NOT NULL AUTO_INCREMENT,
    student_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    enrolled_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (enrollment_id),
    UNIQUE KEY uk_enrollment_unique (student_id, section_id),
    INDEX idx_enrollment_student (student_id),
    INDEX idx_enrollment_section (section_id),
    CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES student_profiles(student_id) ON UPDATE CASCADE,
    CONSTRAINT fk_enrollment_section FOREIGN KEY (section_id) REFERENCES class_sections(section_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 9: classrooms
-- Physical classrooms with GPS coordinates
-- ============================================
CREATE TABLE classrooms (
    classroom_id BIGINT NOT NULL AUTO_INCREMENT,
    room_name VARCHAR(100) NOT NULL,
    building_name VARCHAR(100) NOT NULL,
    floor_number INT,
    latitude DECIMAL(10, 7) NOT NULL,
    longitude DECIMAL(10, 7) NOT NULL,
    allowed_radius_meters INT NOT NULL DEFAULT 50,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (classroom_id),
    UNIQUE KEY uk_classroom_room (room_name, building_name),
    INDEX idx_classroom_active (is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 10: attendance_sessions
-- Attendance sessions created by faculty
-- ============================================
CREATE TABLE attendance_sessions (
    session_id BIGINT NOT NULL AUTO_INCREMENT,
    subject_id BIGINT NOT NULL,
    faculty_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    classroom_id BIGINT NOT NULL,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    session_status ENUM('SCHEDULED', 'ACTIVE', 'CLOSED') NOT NULL DEFAULT 'SCHEDULED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (session_id),
    INDEX idx_session_subject (subject_id),
    INDEX idx_session_faculty (faculty_id),
    INDEX idx_session_section (section_id),
    INDEX idx_session_classroom (classroom_id),
    INDEX idx_session_date (session_date),
    INDEX idx_session_status (session_status),
    INDEX idx_session_date_status (session_date, session_status),
    CONSTRAINT fk_session_subject FOREIGN KEY (subject_id) REFERENCES subjects(subject_id) ON UPDATE CASCADE,
    CONSTRAINT fk_session_faculty FOREIGN KEY (faculty_id) REFERENCES faculty_profiles(faculty_id) ON UPDATE CASCADE,
    CONSTRAINT fk_session_section FOREIGN KEY (section_id) REFERENCES class_sections(section_id) ON UPDATE CASCADE,
    CONSTRAINT fk_session_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms(classroom_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 11: registered_devices
-- Student device registration with public keys
-- ============================================
CREATE TABLE registered_devices (
    device_id BIGINT NOT NULL AUTO_INCREMENT,
    student_id BIGINT NOT NULL,
    device_name VARCHAR(150) NOT NULL,
    public_key TEXT NOT NULL,
    key_algorithm VARCHAR(20) NOT NULL DEFAULT 'EC',
    device_status ENUM('ACTIVE', 'REVOKED') NOT NULL DEFAULT 'ACTIVE',
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at DATETIME NULL,
    revocation_reason VARCHAR(255) NULL,
    PRIMARY KEY (device_id),
    INDEX idx_device_student (student_id),
    INDEX idx_device_status (device_status),
    CONSTRAINT fk_device_student FOREIGN KEY (student_id) REFERENCES student_profiles(student_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 12: qr_tokens
-- Dynamic QR tokens with hash-based verification
-- ============================================
CREATE TABLE qr_tokens (
    qr_id BIGINT NOT NULL AUTO_INCREMENT,
    session_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    issued_at DATETIME NOT NULL,
    expires_at DATETIME NOT NULL,
    token_status ENUM('ACTIVE', 'EXPIRED', 'REVOKED') NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (qr_id),
    UNIQUE KEY uk_qr_token_hash (token_hash),
    INDEX idx_qr_session (session_id),
    INDEX idx_qr_status (token_status),
    INDEX idx_qr_expires (expires_at),
    CONSTRAINT fk_qr_session FOREIGN KEY (session_id) REFERENCES attendance_sessions(session_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 13: attendance_attempts
-- Tracks each scan attempt with reservation
-- ============================================
CREATE TABLE attendance_attempts (
    attempt_id BIGINT NOT NULL AUTO_INCREMENT,
    student_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    device_id BIGINT NULL,
    request_id VARCHAR(100) NOT NULL,
    qr_id BIGINT NOT NULL,
    scan_time DATETIME NOT NULL,
    reservation_expires_at DATETIME NOT NULL,
    verification_status ENUM('PENDING', 'VERIFIED', 'REJECTED', 'EXPIRED') NOT NULL DEFAULT 'PENDING',
    rejection_reason VARCHAR(500) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (attempt_id),
    UNIQUE KEY uk_attempt_request (request_id),
    INDEX idx_attempt_student (student_id),
    INDEX idx_attempt_session (session_id),
    INDEX idx_attempt_device (device_id),
    INDEX idx_attempt_qr (qr_id),
    INDEX idx_attempt_status (verification_status),
    INDEX idx_attempt_reservation (reservation_expires_at),
    INDEX idx_attempt_student_session (student_id, session_id),
    CONSTRAINT fk_attempt_student FOREIGN KEY (student_id) REFERENCES student_profiles(student_id) ON UPDATE CASCADE,
    CONSTRAINT fk_attempt_session FOREIGN KEY (session_id) REFERENCES attendance_sessions(session_id) ON UPDATE CASCADE,
    CONSTRAINT fk_attempt_device FOREIGN KEY (device_id) REFERENCES registered_devices(device_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_attempt_qr FOREIGN KEY (qr_id) REFERENCES qr_tokens(qr_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 14: attendance_records
-- Final verified attendance records
-- ============================================
CREATE TABLE attendance_records (
    attendance_id BIGINT NOT NULL AUTO_INCREMENT,
    student_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    attempt_id BIGINT NULL,
    attendance_status ENUM('PRESENT', 'ABSENT') NOT NULL,
    marked_at DATETIME NOT NULL,
    latitude DECIMAL(10, 7) NULL,
    longitude DECIMAL(10, 7) NULL,
    gps_accuracy_meters DECIMAL(8, 2) NULL,
    distance_from_classroom DECIMAL(8, 2) NULL,
    verification_method VARCHAR(100) NULL,
    manual_override BOOLEAN NOT NULL DEFAULT FALSE,
    override_reason VARCHAR(500) NULL,
    override_by BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (attendance_id),
    UNIQUE KEY uk_attendance_student_session (student_id, session_id),
    UNIQUE KEY uk_attendance_attempt (attempt_id),
    INDEX idx_attendance_student (student_id),
    INDEX idx_attendance_session (session_id),
    INDEX idx_attendance_status (attendance_status),
    INDEX idx_attendance_marked (marked_at),
    CONSTRAINT fk_attendance_student FOREIGN KEY (student_id) REFERENCES student_profiles(student_id) ON UPDATE CASCADE,
    CONSTRAINT fk_attendance_session FOREIGN KEY (session_id) REFERENCES attendance_sessions(session_id) ON UPDATE CASCADE,
    CONSTRAINT fk_attendance_attempt FOREIGN KEY (attempt_id) REFERENCES attendance_attempts(attempt_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_attendance_override_by FOREIGN KEY (override_by) REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 15: verification_logs
-- Detailed verification step logs
-- ============================================
CREATE TABLE verification_logs (
    log_id BIGINT NOT NULL AUTO_INCREMENT,
    attempt_id BIGINT NOT NULL,
    verification_type ENUM('QR', 'GPS', 'DEVICE', 'ENROLLMENT', 'DUPLICATE', 'RESERVATION') NOT NULL,
    verification_result ENUM('PASSED', 'FAILED') NOT NULL,
    details VARCHAR(500) NULL,
    checked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (log_id),
    INDEX idx_vlog_attempt (attempt_id),
    INDEX idx_vlog_type (verification_type),
    INDEX idx_vlog_result (verification_result),
    CONSTRAINT fk_vlog_attempt FOREIGN KEY (attempt_id) REFERENCES attendance_attempts(attempt_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 16: device_challenges
-- Challenge-response for device authentication
-- ============================================
CREATE TABLE device_challenges (
    challenge_id BIGINT NOT NULL AUTO_INCREMENT,
    device_id BIGINT NOT NULL,
    challenge_value VARCHAR(255) NOT NULL,
    challenge_hash CHAR(64) NOT NULL,
    expires_at DATETIME NOT NULL,
    consumed BOOLEAN NOT NULL DEFAULT FALSE,
    consumed_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (challenge_id),
    INDEX idx_challenge_device (device_id),
    INDEX idx_challenge_hash (challenge_hash),
    INDEX idx_challenge_expires (expires_at),
    CONSTRAINT fk_challenge_device FOREIGN KEY (device_id) REFERENCES registered_devices(device_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================
-- TABLE 17: audit_logs
-- System-wide audit trail
-- ============================================
CREATE TABLE audit_logs (
    log_id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NULL,
    action VARCHAR(150) NOT NULL,
    entity_type VARCHAR(100) NULL,
    entity_id BIGINT NULL,
    description VARCHAR(500) NULL,
    ip_address VARCHAR(45) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (log_id),
    INDEX idx_audit_user (user_id),
    INDEX idx_audit_action (action),
    INDEX idx_audit_entity (entity_type, entity_id),
    INDEX idx_audit_created (created_at),
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

